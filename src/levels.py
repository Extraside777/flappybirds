# -- рівні складності: що більший рахунок, то швидше летять труби, вужчий прохід між верхньою і нижньою
# -- трубою і ближче труби одна до одної (на екрані їх більше). Останній рівень триває до кінця гри.
#    score   -- з якого рахунку починається рівень
#    speed   -- px за кадр, з якою швидкістю їдуть труби (і весь світ)
#    gap     -- висота проходу між верхньою і нижньою трубою
#    spacing -- відстань між трубами по горизонталі
LEVELS = [
    {"score": 0, "speed": 3.0, "gap": 150, "spacing": 250},
    {"score": 10, "speed": 3.3, "gap": 144, "spacing": 240},
    {"score": 20, "speed": 3.6, "gap": 138, "spacing": 230},
    {"score": 30, "speed": 3.9, "gap": 132, "spacing": 220},
    {"score": 45, "speed": 4.2, "gap": 126, "spacing": 210},
    {"score": 60, "speed": 4.5, "gap": 120, "spacing": 200},
]


def level_for(score):
    """номер рівня (0 -- перший) для рахунку"""
    return max(i for i, lv in enumerate(LEVELS) if score >= lv["score"])
